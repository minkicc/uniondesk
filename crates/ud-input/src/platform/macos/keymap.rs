pub fn vk_to_hid(vk: u16) -> Option<KeyCode> {
    VK_TO_HID
        .iter()
        .find(|(code, _)| *code == vk)
        .map(|(_, hid)| KeyCode(*hid))
}

pub fn hid_to_vk(code: KeyCode) -> Option<u16> {
    VK_TO_HID
        .iter()
        .find(|(_, hid)| *hid == code.0)
        .map(|(vk, _)| *vk)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_round_trip() {
        assert_eq!(vk_to_hid(0x00), Some(KeyCode(0x04)));
        assert_eq!(hid_to_vk(KeyCode(0x04)), Some(0x00));
    }

    #[test]
    fn entries_are_unique_per_hid_usage() {
        let mut seen = std::collections::HashSet::new();
        for (vk, hid) in VK_TO_HID {
            // Numpad enter and Clear legitimately share codes with other keys
            // on this platform, so only assert the common table is sane.
            if *hid == 0x58 || *hid == 0x53 {
                continue;
            }
            assert!(seen.insert(*hid), "duplicate hid {hid:#x} at vk {vk:#x}");
        }
    }
}
