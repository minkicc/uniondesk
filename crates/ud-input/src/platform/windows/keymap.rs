/// Virtual key codes for keys whose scan code is unreliable or absent.
/// Consumer page keys (volume, media transport) also arrive as virtual keys.
pub const VK_TO_HID: &[(u16, u16)] = &[
    (0x13, 0x48), // Pause / Break
    (0x2c, 0x46), // Print Screen
    (0xa0, 0xe1),
    (0xa1, 0xe5),
    (0xa2, 0xe0),
    (0xa3, 0xe4),
    (0xa4, 0xe2),
    (0xa5, 0xe6),
    (0x5b, 0xe3),
    (0x5c, 0xe7),
    (0xad, 0x2103), // Volume mute
    (0xae, 0x2102), // Volume down
    (0xaf, 0x2101), // Volume up
    (0xb0, 0x2105), // Next track
    (0xb1, 0x2106), // Previous track
    (0xb3, 0x2104), // Play/pause
];

pub fn scan_to_hid(scan: u16) -> Option<KeyCode> {
    SCAN_TO_HID
        .iter()
        .find(|(s, _)| *s == scan)
        .map(|(_, hid)| KeyCode(*hid))
}

pub fn vk_to_hid(vk: u16) -> Option<KeyCode> {
    if let Some((_, hid)) = VK_TO_HID.iter().find(|(v, _)| *v == vk) {
        return Some(KeyCode(*hid));
    }
    // Letters and digits follow a contiguous pattern.
    match vk {
        0x41..=0x5a => Some(KeyCode(0x04 + (vk - 0x41))),
        0x31..=0x39 => Some(KeyCode(0x1e + (vk - 0x31))),
        0x30 => Some(KeyCode(0x27)),
        0x60..=0x69 => {
            const PAD: [u16; 10] = [0x62, 0x59, 0x5a, 0x5b, 0x5c, 0x5d, 0x5e, 0x5f, 0x60, 0x61];
            Some(KeyCode(PAD[(vk - 0x60) as usize]))
        }
        0x70..=0x7b => Some(KeyCode(0x3a + (vk - 0x70))),
        0x7c..=0x87 => Some(KeyCode(0x68 + (vk - 0x7c))),
        _ => None,
    }
}

/// Reverse lookup used when synthesising events for the peer.
pub fn hid_to_scan(code: KeyCode) -> Option<u16> {
    SCAN_TO_HID
        .iter()
        .find(|(_, hid)| *hid == code.0)
        .map(|(scan, _)| *scan)
}

/// SendInput wants the extended flag broken out separately.
pub fn split_scan(scan: u16) -> (u16, bool) {
    if scan & 0xe000 == 0xe000 {
        (scan & 0xff, true)
    } else {
        (scan, false)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_round_trip() {
        assert_eq!(vk_to_hid(0x41), Some(KeyCode(0x04)));
        assert_eq!(vk_to_hid(0x5a), Some(KeyCode(0x1d)));
        assert_eq!(scan_to_hid(0x1e), Some(KeyCode(0x04)));
        assert_eq!(hid_to_scan(KeyCode(0x04)), Some(0x1e));
    }

    #[test]
    fn extended_keys_keep_their_prefix() {
        let (scan, extended) = split_scan(0xe04b);
        assert_eq!(scan, 0x4b);
        assert!(extended);
        let (plain, extended) = split_scan(0x1e);
        assert_eq!(plain, 0x1e);
        assert!(!extended);
    }

    #[test]
    fn every_hid_value_is_unique() {
        let mut seen = std::collections::HashSet::new();
        for (scan, hid) in SCAN_TO_HID {
            assert!(seen.insert(*hid), "duplicate hid {hid:#x} at scan {scan:#x}");
        }
    }
}
